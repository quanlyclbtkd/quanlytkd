import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {runtimeHash} from '../v11r2/cutover.mjs';
import {verifySourceIdentity} from '../v11r2/source-identity.mjs';
import {casContract} from '../v11/cas-contract.mjs';
import {HISTORY_AUTHORITY,JOURNAL_DATABASE} from '../../js/core/attendanceContract.js';
const sha=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const identity=verifySourceIdentity(process.cwd(),runtimeHash(process.cwd()));
assert.equal(identity.id,'V11R6_A9R13_MEMBER_HISTORY_DIAGNOSTICS');
assert.equal(identity.canonicalFileCount,128);
const manifest=JSON.parse(fs.readFileSync(identity.manifest,'utf8'));
for(const file of Object.keys(manifest.canonicalRuntimeFiles))assert.equal(sha(fs.readFileSync(file)),sha(fs.readFileSync(path.join('public',file))),file+' root/public parity');
assert.equal(sha(fs.readFileSync('firestore.rules')),'1aa7fd38544142dcb82dbd8809f9ea65d6c77dc6427f60934e3333005062e6b3');
assert.equal(HISTORY_AUTHORITY,'attendance-history-1aedda93-9437-4132-9694-35c2e6234d55');
assert.equal(JOURNAL_DATABASE,'tst-attendance-journal-v4');
const cas=await casContract();
const report={kind:'A9R13_OFFLINE_INVARIANTS',sourceIdentity:identity.id,canonicalFileCount:128,rootPublicParity:'128/128',rulesUnchanged:true,authorityUnchanged:true,journalUnchanged:true,cas:cas.results};
fs.mkdirSync('evidence/A9R13',{recursive:true});fs.writeFileSync('evidence/A9R13/OFFLINE_INVARIANTS.json',JSON.stringify(report,null,2));
console.log('A9R13 source identity PASS; root/public 128/128; unchanged Rules/authority/Journal V4; CAS '+cas.results.length+' PASS');
