#!/usr/bin/env node
import fs from 'node:fs';
let pass=0,fail=0; const c=(n,x,d='')=>x?(pass++,console.log('✅',n)):(fail++,console.error('❌',n,d));
const src=fs.readFileSync('js/modules/students.js','utf8');
const service=fs.readFileSync('js/services/students.service.js','utf8');
const att=fs.readFileSync('js/modules/attendance.js','utf8');
const start=src.indexOf('window.updateProfile = async () =>');
const end=src.indexOf('window.deleteProfile = async',start);
const fn=src.slice(start,end);
c('displayName edit supported', /requestedDisplayName/.test(fn) && /displayName:\s*requestedDisplayName/.test(fn));
c('profileKey remains immutable modal identity', /const profileKey\s*=\s*document\.getElementById\('m_old_name'\)/.test(fn));
c('canonical command receives oldName/newName as same profileKey', /oldName:\s*profileKey[\s\S]{0,100}newName:\s*profileKey/.test(fn));
c('display edit has zero renameWithBatch call', !/renameWithBatch/.test(fn));
c('display edit has zero transaction lookup', !/findTransactionsByStudent/.test(fn));
c('display edit has zero profile delete/create branch', !/deleteProfile|createProfile|deleteDoc\s*\(|writeBatch\s*\(/.test(fn));
c('legacy rename service retained only for compatibility', /renameWithBatch/.test(service));
c('no Attendance historical migration added to profile edit flow', !/AttendanceService|attendance\//.test(fn));
c('no historical transaction rewrite added to profile edit flow', !/txUpdates|newDesc|transactions/.test(fn));
c('Attendance identity primitives remain profile-key based', /getAttendanceDocId\(name,/.test(att) && /currentAttendanceData\[name\]/.test(att));
c('no startup/background rename repair added', !/setInterval[\s\S]{0,200}rename|setTimeout[\s\S]{0,200}rename/i.test(src));
console.log(`PASS ${pass}/${pass+fail}`); if(fail)process.exit(1);
