import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const original = fs.readFileSync(process.env.R5_AUDIT_SCRIPT || 'handoff/V11R5/references/projection_ack_snapshot_race.mjs', 'utf8');
const source = path.resolve('js/modules/finance/finance.pagination.js');
const portable = original.replace(/^const source = .*;$/m, 'const source = ' + JSON.stringify(source) + ';');
assert.notEqual(portable, original);
const r = spawnSync(process.execPath, ['--input-type=module', '-e', portable], { encoding: 'utf8' });
const rows = [...r.stdout.matchAll(/\{[\s\S]*?\}/g)].map(m => JSON.parse(m[0]));
assert.equal(r.status, 0, r.stderr);
assert.equal(rows.length, 4);
const expectedDefect = process.env.R5_EXPECT_DEFECT === 'true';
assert.equal(rows[0].defectReproduced, expectedDefect);
assert.equal(rows[1].visible.length, 1); assert.equal(rows[2].visible.length, 1); assert.equal(rows[3].visible.length, 0);
const out = process.env.R5_AUDIT_EVIDENCE || 'handoff/V11R5/evidence/independent-audit-replay';
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out + '.log', r.stdout + r.stderr);
fs.writeFileSync(out + '.json', JSON.stringify({ command: ['node', 'tools/v11r5/replay-independent-audit.mjs'], sourceSHA: createHash('sha256').update(fs.readFileSync(source)).digest('hex'), originalScriptSHA: createHash('sha256').update(original).digest('hex'), modification: 'Only hardcoded source path replaced for portability; four test bodies unchanged', expectedDefect, expectedExit: 0, actualExit: 0, status: 'PASS', results: rows }, null, 2));
console.log(expectedDefect ? 'PASS R4 independent counterexample reproduced' : 'PASS independent counterexample closed; all negative controls pass');
