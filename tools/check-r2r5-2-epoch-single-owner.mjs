#!/usr/bin/env node
import fs from 'node:fs';
let pass=0,fail=0; const check=(name,cond,detail='')=>{if(cond){pass++;console.log('PASS',name)}else{fail++;console.error('FAIL',name,detail)}};
globalThis.window=globalThis; globalThis.addEventListener=()=>{};
globalThis.getAccountingComponents=tx=>Array.isArray(tx?.components)?tx.components:[];
globalThis.isTuitionFinanceTransaction=tx=>globalThis.getAccountingComponents(tx).some(c=>c?.kind==='tuition');
globalThis.classifyInventoryFinanceTx=tx=>({isInventory:globalThis.getAccountingComponents(tx).some(c=>c?.kind==='inventory')});
globalThis.invCustomCategories=[];
const {installSemanticSourceEpochBridge}=await import(`../js/store.js?r2r52epoch=${Date.now()}`);
const st={clubId:'C1',currentClubId:'C1',transactions:[],clubConfig:{branchCount:2},_transactionsVersion:0,_tuitionEvidenceVersion:0,_inventoryTxVersion:0,_examTxVersion:0,_settingsVersion:0,_inventoryCategoryVersion:0};
installSemanticSourceEpochBridge(st,globalThis);
let before=st._transactionsVersion;
st.transactions=[{id:'T1',components:[{kind:'tuition'}]}];
check('one canonical transaction assignment increments transactions epoch exactly once',st._transactionsVersion-before===1,{before,after:st._transactionsVersion});
check('tuition semantic effect increments tuition epoch exactly once',st._tuitionEvidenceVersion===1,st._tuitionEvidenceVersion);
before=st._transactionsVersion; st.transactions=[{id:'T1',components:[{kind:'tuition'}]}];
check('equivalent transaction assignment does not churn epoch',st._transactionsVersion===before,{before,after:st._transactionsVersion});
let catBefore=st._inventoryCategoryVersion; globalThis.invCustomCategories=['A'];
check('one inventory category assignment increments category epoch exactly once',st._inventoryCategoryVersion-catBefore===1,{before:catBefore,after:st._inventoryCategoryVersion});
catBefore=st._inventoryCategoryVersion; globalThis.invCustomCategories=['A'];
check('equivalent inventory category assignment does not churn epoch',st._inventoryCategoryVersion===catBefore);
let settingsBefore=st._settingsVersion; st.clubConfig={...st.clubConfig,canonicalTransactionReadMonths:['2026-10']};
check('one relevant immutable settings assignment increments settings epoch exactly once',st._settingsVersion-settingsBefore===1,{before:settingsBefore,after:st._settingsVersion});
settingsBefore=st._settingsVersion; st.clubConfig={...st.clubConfig};
check('equivalent settings assignment does not churn epoch',st._settingsVersion===settingsBefore);
const tuition=fs.readFileSync('js/core/tuitionCommandBoundary.js','utf8');
const inv=fs.readFileSync('js/modules/inventory.js','utf8');
const txBoundary=fs.readFileSync('js/core/transactionCanonicalBoundary.js','utf8');
check('Tuition command has no direct _transactionsVersion writer',!/\._transactionsVersion\s*(?:\+\+|\+=|=)/.test(tuition));
check('Inventory UI has no direct _inventoryCategoryVersion writer',!/_inventoryCategoryVersion\s*(?:\+\+|\+=|=)/.test(inv));
check('canonicalTransactionReadMonths mutation routes through clubConfig assignment',/store\.clubConfig\s*=\s*\{[\s\S]{0,180}canonicalTransactionReadMonths/.test(txBoundary));
console.log(`\nR2R5.2 epoch single-owner: ${pass} PASS / ${fail} FAIL`); if(fail)process.exit(1);
