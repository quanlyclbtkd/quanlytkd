#!/usr/bin/env node
// Security-first RELEASE GATE: do not trust PASS/APPROVED string markers in Markdown.
// Must execute the real Emulator test and require an independently provided cost decision.
import {spawnSync} from 'node:child_process';
import {readFileSync,existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
const failures=[];
const sha=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
const src=readFileSync('js/listeners/profiles.listeners.js','utf8');
if(/activeQuery\s*=\s*fbQuery\(profRef,\s*statusConstraint/.test(src)||/legacyQuery\s*=\s*fbQuery\(profRef,\s*statusConstraint/.test(src)){
 failures.push('E01: Coach listeners still use status-prefiltered queries');
}
const behavioral=spawnSync(process.execPath,['tools/check-d1c3b7-provisional-coach.mjs'],{encoding:'utf8',timeout:20000});
process.stdout.write(behavioral.stdout||'');process.stderr.write(behavioral.stderr||'');
if(behavioral.status!==0) failures.push('E01/E02 actual-handler behavioral matrix fails (exit '+behavioral.status+')');
const r1=spawnSync(process.execPath,['tools/check-d1c3b7r1-coach-roster-closure.mjs'],{encoding:'utf8',timeout:30000});
process.stdout.write(r1.stdout||'');process.stderr.write(r1.stderr||'');
if(r1.status!==0) failures.push('R1 branch-only roster actual-handler matrix fails (exit '+r1.status+')');
// Native Firebase CLI and exact source's existing Rules. Running this in a real
// emulator also tests branch-specific allow/deny, alias and legacy coverage.
const cli=spawnSync('firebase',['--version'],{encoding:'utf8',timeout:8000});
if(cli.error||cli.status!==0){failures.push('Rules Emulator NOT VERIFIED: Firebase CLI unavailable');}
else{
 const test=spawnSync('firebase',['emulators:exec','--only','firestore','--project','demo-b7-coach-proof','node tools/check-d1c3b7-rules-principals.mjs'],{encoding:'utf8',timeout:180000});
 process.stdout.write(test.stdout||'');process.stderr.write(test.stderr||'');
 if(test.status!==0) failures.push('Real Firestore Rules allow/deny principal test failed/not completed ('+test.status+')');
}
// The owner must supply this file separately, not generated by the assistant's
// reports. Source/rules hashes, tested population and bounded cost decision are
// compared with the exact release candidate at execution time.
const path=process.env.D1C3B7_COST_APPROVAL_FILE;
if(!path||!existsSync(path)) failures.push('Document-read cost authorization absent (owner-supplied record required)');
else try{
 const a=JSON.parse(readFileSync(path,'utf8'));
 const approvalOk=a.decision==='approved'&&a.issuedBy==='system_owner'&&typeof a.approvedAt==='string'&&
   a.rulesSha256===sha('firestore.rules')&&a.sourceSha256===sha('js/listeners/profiles.listeners.js')&&
   Number.isFinite(a.maxIncrementalInitialDocs)&&a.maxIncrementalInitialDocs>=0&&
   a.profilesMeasured1000===true&&a.profilesMeasured1500===true&&
   typeof a.scope==='string'&&a.scope.includes('Coach CS1')&&a.scope.includes('CS2');
 if(!approvalOk) failures.push('Owner approval missing exact scope/hash/measurement');
}catch(e){failures.push('Owner approval invalid JSON: '+e.message)}
for(const f of failures)console.error('B7 RELEASE BLOCKER:',f);
if(failures.length){console.error('D1C3B7 RELEASE BLOCKED',failures.length);process.exitCode=1}
else console.log('D1C3B7 SECURITY RELEASE CHECK PASS');
